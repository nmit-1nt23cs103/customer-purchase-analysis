"""Step 4 - run the SQL reporting queries and chart the headline results."""
from __future__ import annotations

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from . import config as C
from .db import connect, load_named_queries
from .plotting import AXIS, CATEGORICAL, INK, INK2, SURFACE, save_fig, style_axes
from .utils import df_to_markdown


def _plot_segment_share(prof: pd.DataFrame):
    fig, ax = plt.subplots(figsize=(8.5, 0.95 * len(prof) + 1.8))
    y = np.arange(len(prof))
    h = 0.36
    b1 = ax.barh(y - h / 2, prof["pct_customers"], h, color=CATEGORICAL[0], label="% of customers",
                 edgecolor=SURFACE, linewidth=1.5)
    b2 = ax.barh(y + h / 2, prof["pct_of_total_spend"], h, color=CATEGORICAL[1], label="% of total spend",
                 edgecolor=SURFACE, linewidth=1.5)
    ax.bar_label(b1, fmt="%.0f%%", padding=3, color=INK2, fontsize=9)
    ax.bar_label(b2, fmt="%.0f%%", padding=3, color=INK2, fontsize=9)
    ax.set_yticks(y, prof["segment_name"])
    ax.invert_yaxis()
    ax.set_xlim(0, max(prof["pct_customers"].max(), prof["pct_of_total_spend"].max()) * 1.18)
    ax.set_xlabel("Percent")
    ax.set_title("Share of customers vs share of spend, by segment")
    style_axes(ax, "x")
    ax.legend(loc="lower right")
    return save_fig(fig, "sql_segment_share.png")


def _plot_concentration(dec: pd.DataFrame):
    x = [0] + list(dec["spend_decile"] * 10)
    y = [0] + list(dec["cumulative_pct"])
    fig, ax = plt.subplots(figsize=(6.4, 4.6))
    ax.plot([0, 100], [0, 100], color=AXIS, linestyle="--", linewidth=1.2)
    ax.text(62, 56, "equal spend per customer", color=INK2, fontsize=9, rotation=34)
    ax.plot(x, y, color=CATEGORICAL[0], linewidth=2, marker="o", markersize=6,
            markeredgecolor=SURFACE, markeredgewidth=1.5)
    ax.annotate(f"Top 10% of customers:\n{y[1]:.0f}% of spend", (x[1], y[1]), textcoords="offset points",
                xytext=(14, -6), color=INK, fontsize=10)
    ax.set_xlim(0, 100)
    ax.set_ylim(0, 100)
    ax.set_xlabel("Cumulative % of customers (highest spenders first)")
    ax.set_ylabel("Cumulative % of total spend")
    ax.set_title("Spend concentration")
    style_axes(ax, "y")
    return save_fig(fig, "sql_spend_concentration.png")


def _key_findings(t: dict[str, pd.DataFrame]) -> list[str]:
    out = []
    dec = t["spend_concentration_by_decile"]
    top = dec.loc[dec["spend_decile"] == 1].iloc[0]
    out.append(f"The top 10% of customers by spend generate **{top['pct_of_total_spend']:.1f}%** of total spend.")

    prof = t["segment_profile"]
    best = prof.iloc[0]
    out.append(
        f"**{best['segment_name']}** is the highest-spending segment: {best['pct_customers']:.1f}% of customers "
        f"but {best['pct_of_total_spend']:.1f}% of total spend."
    )
    best_resp = prof.sort_values("response_rate_pct", ascending=False).iloc[0]
    out.append(
        f"**{best_resp['segment_name']}** responds best to the latest campaign "
        f"({best_resp['response_rate_pct']:.1f}% vs {t['overview'].iloc[0]['response_rate_pct']:.1f}% overall)."
    )

    eng = t["prior_campaign_engagement"].set_index("prior_campaigns_accepted")
    if {"None", "1 or more"} <= set(eng.index):
        out.append(
            f"Customers who accepted at least one earlier campaign respond at "
            f"{eng.loc['1 or more', 'response_rate_pct']:.1f}%, versus {eng.loc['None', 'response_rate_pct']:.1f}% "
            f"for those who never did."
        )

    risk = t["high_value_at_risk_by_segment"]
    if len(risk):
        out.append(
            f"{int(risk['at_risk_customers'].sum())} top-quartile spenders have not purchased in 60+ days "
            f"(about {risk['spend_at_risk'].sum():,.0f} in historical spend) - prime retention targets."
        )
    return out


def run() -> dict:
    queries = load_named_queries(C.SQL_DIR / "analysis.sql")
    C.SQL_RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    tables: dict[str, pd.DataFrame] = {}
    report = ["# SQL analysis report\n", "Generated by `python -m src.sql_analysis` from `sql/analysis.sql`.\n"]
    with connect() as conn:
        for name, (sql, desc) in queries.items():
            df = pd.read_sql_query(sql, conn)
            df.to_csv(C.SQL_RESULTS_DIR / f"{name}.csv", index=False)
            tables[name] = df
            report += [f"\n## {name}\n", f"{desc}\n", f"```sql\n{sql}\n```\n", df_to_markdown(df.head(25)), ""]
    (C.REPORT_DIR / "sql_report.md").write_text("\n".join(report), encoding="utf-8")

    figs = [_plot_segment_share(tables["segment_profile"]), _plot_concentration(tables["spend_concentration_by_decile"])]
    findings = _key_findings(tables)

    prof = tables["segment_profile"].drop(columns=["segment_id"]).rename(columns={
        "segment_name": "segment", "pct_customers": "% customers", "avg_income": "avg income",
        "avg_age": "avg age", "avg_children": "avg children", "avg_spend": "avg spend",
        "pct_of_total_spend": "% of total spend", "response_rate_pct": "response rate %"})
    summary = (
        "### SQL analysis (SQLite)\n\n"
        f"{len(queries)} queries in [`sql/analysis.sql`](sql/analysis.sql) use joins, CTEs, CASE bucketing, "
        "window functions (`NTILE`, `PERCENT_RANK`, running `SUM`) and sub-queries. "
        "Full output: `reports/sql_report.md`.\n\n"
        + "\n".join(f"- {f}" for f in findings)
        + f"\n\n{df_to_markdown(prof, float_digits=1)}\n\n"
        "![Share of customers vs spend]({FIG}/sql_segment_share.png)\n\n"
        "![Spend concentration]({FIG}/sql_spend_concentration.png)\n"
    )
    print(f"Ran {len(queries)} SQL queries -> {C.SQL_RESULTS_DIR}")
    return {"tables": tables, "findings": findings, "summary_md": summary, "figures": [f.name for f in figs]}


if __name__ == "__main__":
    run()
